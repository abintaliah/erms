CREATE FUNCTION enforce_one_enabled_default_language() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT count(*) FROM supported_languages WHERE is_default AND is_enabled) <> 1 THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='exactly_one_enabled_default_language_required';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER supported_languages_require_one_default
AFTER INSERT OR UPDATE OR DELETE ON supported_languages
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION enforce_one_enabled_default_language();

CREATE TABLE user_preferences (
    user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    language_tag text NOT NULL REFERENCES supported_languages(language_tag) ON DELETE RESTRICT,
    working_timezone text NOT NULL,
    date_created timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_updated timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version bigint NOT NULL DEFAULT 1,
    CONSTRAINT user_preferences_timezone_not_blank CHECK (btrim(working_timezone) <> ''),
    CONSTRAINT user_preferences_version_positive CHECK (version > 0)
);

CREATE FUNCTION touch_localization_row() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.date_updated := CURRENT_TIMESTAMP;
    NEW.version := OLD.version + 1;
    RETURN NEW;
END;
$$;
CREATE TRIGGER supported_languages_touch BEFORE UPDATE ON supported_languages
FOR EACH ROW EXECUTE FUNCTION touch_localization_row();
CREATE TRIGGER user_preferences_touch BEFORE UPDATE ON user_preferences
FOR EACH ROW EXECUTE FUNCTION touch_localization_row();

CREATE TRIGGER supported_languages_record_history
AFTER INSERT OR UPDATE OR DELETE ON supported_languages
FOR EACH ROW EXECUTE FUNCTION record_entity_history('supported_language');

CREATE FUNCTION record_user_preference_history() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    old_state jsonb;
    new_state jsonb;
    changed text[];
BEGIN
    old_state := CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) END;
    new_state := CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN to_jsonb(NEW) END;
    SELECT COALESCE(array_agg(key ORDER BY key),ARRAY[]::text[]) INTO changed
      FROM jsonb_object_keys(COALESCE(old_state,'{}'::jsonb) || COALESCE(new_state,'{}'::jsonb)) key
     WHERE old_state -> key IS DISTINCT FROM new_state -> key;
    INSERT INTO event_history(
        entity_type,entity_id,operation,actor_user_id,actor_type,source,
        request_id,correlation_id,before_state,after_state,changed_fields,reason,metadata
    ) VALUES (
        'user_preference',CASE WHEN TG_OP='DELETE' THEN OLD.user_id ELSE NEW.user_id END,
        CASE TG_OP WHEN 'INSERT' THEN 'CREATE' ELSE TG_OP END,
        NULLIF(current_setting('app.user_id',true),'')::bigint,
        COALESCE(NULLIF(current_setting('app.actor_type',true),''),'automated_process'),
        COALESCE(NULLIF(current_setting('app.event_source',true),''),'database'),
        NULLIF(current_setting('app.request_id',true),'')::uuid,
        NULLIF(current_setting('app.correlation_id',true),'')::uuid,
        old_state,new_state,changed,
        NULLIF(current_setting('app.change_reason',true),''),
        COALESCE(NULLIF(current_setting('app.event_metadata',true),'')::jsonb,'{}'::jsonb)
    );
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END;
$$;
CREATE TRIGGER user_preferences_record_history
AFTER INSERT OR UPDATE OR DELETE ON user_preferences
FOR EACH ROW EXECUTE FUNCTION record_user_preference_history();

