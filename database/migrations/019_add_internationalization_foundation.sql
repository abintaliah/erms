CREATE TABLE supported_languages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language_tag text NOT NULL UNIQUE,
    english_name text NOT NULL,
    native_name text NOT NULL,
    direction text NOT NULL,
    is_enabled boolean NOT NULL DEFAULT true,
    is_default boolean NOT NULL DEFAULT false,
    formatting_config jsonb NOT NULL DEFAULT '{}'::jsonb,
    catalogue_revision bigint NOT NULL DEFAULT 1,
    date_created timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_updated timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version bigint NOT NULL DEFAULT 1,
    CONSTRAINT supported_languages_tag_shape CHECK (
        language_tag ~ '^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*$'
    ),
    CONSTRAINT supported_languages_english_name_not_blank CHECK (btrim(english_name) <> ''),
    CONSTRAINT supported_languages_native_name_not_blank CHECK (btrim(native_name) <> ''),
    CONSTRAINT supported_languages_direction_valid CHECK (direction IN ('ltr','rtl')),
    CONSTRAINT supported_languages_default_enabled CHECK (NOT is_default OR is_enabled),
    CONSTRAINT supported_languages_formatting_object CHECK (jsonb_typeof(formatting_config) = 'object'),
    CONSTRAINT supported_languages_revision_positive CHECK (catalogue_revision > 0),
    CONSTRAINT supported_languages_version_positive CHECK (version > 0)
);
CREATE UNIQUE INDEX supported_languages_one_default_idx
    ON supported_languages ((is_default)) WHERE is_default;
CREATE UNIQUE INDEX supported_languages_tag_ci_unique ON supported_languages(lower(language_tag));

